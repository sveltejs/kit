import fs from 'node:fs';
import process from 'node:process';

/**
 * @typedef {{
 *   name: string;
 *   test: () => boolean;
 *   defaults: import('./index.js').AdapterOptions;
 *   done: (builder: import('@sveltejs/kit').Builder) => void;
 * }}
 * Platform */

// Vercel serves files named `index.*` at their directory's path, so prerendered pages that
// have a trailing slash are renamed to something else when every route has one
const INDEX_FILE = '__index.html';

/** @param {string} str */
function escape_regex(str) {
	return str.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}

// `decodeURI` leaves the escapes of these characters intact: ; / ? : @ & = + $ , #
const RESERVED_ESCAPE = /(%(?:2[346BCF]|3[ABDF]|40))/i;

/**
 * Encodes a pathname decoded by `decodeURI` back into the form a browser requests it in,
 * without encoding the escapes that `decodeURI` left intact a second time.
 * This function is duplicated in adapter-vercel
 * @param {string} pathname
 */
function encode_pathname(pathname) {
	return pathname
		.split(RESERVED_ESCAPE)
		.map((part, i) => (i % 2 === 1 ? part : encodeURI(part)))
		.join('');
}

// Vercel rejects routes whose `src` is longer than 4096 characters
const MAX_SRC_LENGTH = 4000;

/**
 * Creates routes that redirect prerendered pages to their canonical trailing slash form.
 * Since Vercel limits the number of routes in a deployment, pathnames are combined into
 * as few routes as possible rather than creating one route per page.
 * This function is duplicated in adapter-vercel
 * @param {string[]} pathnames decoded pathnames without leading or trailing slashes
 * @param {boolean} trailing_slash `true` if the redirect should add a trailing slash, `false` if it should remove it
 */
function trailing_slash_redirects(pathnames, trailing_slash) {
	/** @type {Array<{ src: string, headers: { Location: string }, status: number, caseSensitive: boolean }>} */
	const routes = [];

	/** @type {string[]} */
	let alternatives = [];
	let length = 0;

	const flush = () => {
		if (alternatives.length === 0) return;

		const group = alternatives.join('|');

		routes.push({
			src: trailing_slash ? `^/(${group})$` : `^/(${group})/$`,
			headers: { Location: trailing_slash ? '/$1/' : '/$1' },
			status: 308,
			caseSensitive: true
		});

		alternatives = [];
		length = 0;
	};

	for (const pathname of pathnames) {
		// Vercel matches against the encoded pathname, so we encode it the way a browser requests it
		const alternative = escape_regex(encode_pathname(pathname));

		if (length + alternative.length + 1 > MAX_SRC_LENGTH) flush();

		alternatives.push(alternative);
		length += alternative.length + 1;
	}

	flush();

	return routes;
}

/**
 * Returns the `trailingSlash` option if every route uses the same one, allowing
 * trailing slashes to be normalized with a single route rather than one per page.
 * Returns `undefined` if the routes disagree, if they use `'ignore'`,
 * or if the version of SvelteKit doesn't expose the option to adapters.
 * This function is duplicated in adapter-vercel
 * @param {Array<{ trailingSlash?: 'never' | 'always' | 'ignore' }>} routes
 * @returns {'never' | 'always' | undefined}
 */
function get_uniform_trailing_slash(routes) {
	const values = new Set(routes.map((route) => route.trailingSlash));
	if (values.size !== 1) return;

	const [value] = values;
	if (value === 'never' || value === 'always') return value;
}

// This function is duplicated in adapter-vercel
/**
 * Escapes a pathname so that it can be matched literally by a Vercel route `src` regex
 * @param {string} pathname
 */
function escape_src(pathname) {
	// hex escapes rather than backslash escapes, since Vercel only appends the `$` anchor
	// if `src` doesn't already end with `$`, and it replaces `\/` with `/`
	return pathname.replace(
		/[.*+?^${}()|[\]\\]/g,
		(char) => `\\x${char.charCodeAt(0).toString(16).padStart(2, '0')}`
	);
}

// This function is duplicated in adapter-vercel
/** @param {import('@sveltejs/kit').Builder} builder */
function static_vercel_config(builder) {
	/** @type {any[]} */
	const prerendered_redirects = [];

	/** @type {Record<string, { path: string }>} */
	const overrides = {};

	for (const [path, redirect] of builder.prerendered.redirects) {
		let src = escape_src(path);

		if (path.replace(/\/$/, '') === redirect.location.replace(/\/$/, '')) {
			// ignore the extreme edge case of a `/foo` -> `/foo/` redirect,
			// which would only arise if the response was generated by a
			// `handle` hook or outside the app altogether (since you
			// can't declaratively create both routes)
		} else {
			// redirect both `/foo` and `/foo/` to `redirect.location`
			src = src.replace(/\/?$/, '/?');
		}

		prerendered_redirects.push({
			src,
			headers: {
				Location: redirect.location
			},
			status: redirect.status
		});
	}

	const base = builder.config.paths.base;
	const trailing_slash = get_uniform_trailing_slash(builder.routes);

	if (base && trailing_slash) {
		// the root of the app always has a trailing slash when `paths.base` is set
		prerendered_redirects.push({
			src: `^${escape_regex(base)}$`,
			headers: { Location: `${base}/` },
			status: 308
		});
	}

	if (trailing_slash === 'never') {
		prerendered_redirects.push({
			src: `^${escape_regex(base)}/(.+)/$`,
			headers: { Location: `${base}/$1` },
			status: 308
		});
	}

	/** @type {string[]} */
	const add_trailing_slash = [];

	/** @type {string[]} */
	const remove_trailing_slash = [];

	for (const [path, page] of builder.prerendered.pages) {
		if (trailing_slash === 'always' && path !== '/' && path.endsWith('/')) {
			// Vercel ignores trailing slashes when looking up static files, and serves `foo/index.html`
			// at `foo`, so we rename the page to stop `/foo` from matching it. That way, `/foo` is
			// redirected after the filesystem phase, while the `miss` route serves the page for `/foo/`.
			// Unlike `page.file`, the path includes the base, which is where the `miss` route looks
			overrides[page.file] = { path: path.slice(1) + INDEX_FILE };
			continue;
		}

		let overrides_path = path.slice(1);

		if (path !== '/') {
			if (path.endsWith('/')) {
				overrides_path = path.slice(1, -1);
				add_trailing_slash.push(overrides_path);
			} else {
				remove_trailing_slash.push(overrides_path);
			}
		}

		overrides[page.file] = { path: overrides_path };
	}

	if (!trailing_slash) {
		// Vercel ignores trailing slashes when looking up static files, so `/foo` and `/foo/`
		// are both served by the `foo` file. We only need routes for the redirects
		prerendered_redirects.push(
			...trailing_slash_redirects(add_trailing_slash, true),
			...trailing_slash_redirects(remove_trailing_slash, false)
		);
	}

	/** @type {any[]} */
	const routes = [
		...prerendered_redirects,
		{
			src: `/${builder.getAppPath()}/immutable/.+`,
			headers: {
				'cache-control': 'public, immutable, max-age=31536000'
			}
		}
	];

	if (trailing_slash === 'always') {
		// serve the renamed page for `/foo/` if it exists. Routes in the `miss` phase
		// are reverted if they don't match a file, so other requests are unaffected
		routes.push({ handle: 'miss' }, { src: '^(/.+)/$', dest: `$1/${INDEX_FILE}`, check: true });
	}

	routes.push(
		{
			handle: 'filesystem'
		},
		// Prevent incorrect caching: if a request to /_app/immutable/* doesn't match
		// a static file, return 404 instead of falling through to dynamic routes.
		// Otherwise, we could accidentally immutably cache dynamic content served
		// by the fallback function. `no-store` stops the earlier immutable header
		// from sticking to this 404, so a missing asset isn't cached for a year.
		{
			src: `/${builder.getAppPath()}/immutable/.+`,
			status: 404,
			headers: {
				'cache-control': 'no-store'
			},
			continue: false
		}
	);

	if (trailing_slash === 'always') {
		// Requests that reach this point didn't match a static file, so we can add a trailing
		// slash without affecting assets. Internal requests are excluded since they never have one
		routes.push({
			src: `^(?!/${escape_regex(builder.getAppPath())}/)(?!.*__(?:data\\.json|route\\.js)$)(${escape_regex(base)}/.*[^/])$`,
			headers: { Location: '$1/' },
			status: 308
		});
	}

	return {
		version: 3,
		routes,
		overrides
	};
}

/** @type {Platform[]} */
export const platforms = [
	{
		name: 'Vercel',
		test: () => !!process.env.VERCEL,
		defaults: {
			pages: '.vercel/output/static'
		},
		done: (builder) => {
			const config = static_vercel_config(builder);
			fs.writeFileSync('.vercel/output/config.json', JSON.stringify(config, null, '  '));
		}
	}
];
