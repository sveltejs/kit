import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import process from 'node:process';
import { describe, test, vi, expect } from 'vitest';
import {
	validate_worker_settings,
	generate_redirects,
	append_headers,
	sync_process_env
} from './utils.js';

describe('validate_worker_settings', () => {
	test('rejects Cloudflare Pages builds', () => {
		vi.stubEnv('CF_PAGES', '1');
		try {
			expect(() => validate_worker_settings()).toThrow('Cloudflare Pages is no longer supported');
		} finally {
			vi.unstubAllEnvs();
		}
	});

	test('accepts Workers builds', () => {
		vi.stubEnv('CF_PAGES', undefined);
		try {
			expect(() => validate_worker_settings()).not.toThrow();
		} finally {
			vi.unstubAllEnvs();
		}
	});
});

describe('_headers', () => {
	test('adds URL and its headers', () => {
		const content = append_headers(
			'/_app/*',
			['X-Robots-Tag: noindex', 'Cache-Control: no-cache'],
			'/custom\n  X-Custom-Rule: value'
		);
		expect(content).toEqual(
			`
/custom
  X-Custom-Rule: value
# === START AUTOGENERATED SVELTE IMMUTABLE HEADERS ===
/_app/*
  X-Robots-Tag: noindex
  Cache-Control: no-cache
# === END AUTOGENERATED SVELTE IMMUTABLE HEADERS ===
`.trim()
		);
	});

	test('adds headers to existing URLs', () => {
		const content = append_headers(
			'/_app/*',
			['X-Robots-Tag: noindex', 'Cache-Control: no-cache'],
			'/_app/*\n  X-Custom-Rule: value'
		);
		expect(content).toEqual(
			`
/_app/*
  X-Robots-Tag: noindex
  Cache-Control: no-cache
  X-Custom-Rule: value
`.trim()
		);
	});
});

describe('_redirects', () => {
	test('generates rules for prerendered redirects', () => {
		const warn = vi.fn();
		const content = generate_redirects(
			new Map([
				['/old', { status: 308, location: '/new' }],
				['/café', { status: 302, location: 'https://example.com/a#b' }]
			]),
			// @ts-ignore
			{ warn }
		);

		expect(content).toBe(
			`
# === START AUTOGENERATED SVELTE PRERENDERED REDIRECTS ===
/old /new 308
/caf%C3%A9 https://example.com/a#b 302
# === END AUTOGENERATED SVELTE PRERENDERED REDIRECTS ===`
		);
		expect(warn).not.toHaveBeenCalled();
	});

	test('escapes prerendered redirects that would inject rules', () => {
		const warn = vi.fn();
		const content = generate_redirects(
			new Map([
				[
					'/account/x /\n/_app/immutable/entry/start.js https://attacker.example/x.js 302\n/zz',
					{ status: 303, location: '/login' }
				],
				['/a\u2028b\u00a0c\rd\te', { status: 303, location: '/login' }],
				['/a #comment', { status: 303, location: '/login?q=a b 200' }],
				['/a?b#c', { status: 303, location: '/login' }],
				['/a"<>`{}^b', { status: 303, location: '/login' }]
			]),
			// @ts-ignore
			{ warn }
		);

		const rules = content.split('\n').filter((line) => line && !line.startsWith('#'));
		expect(rules).toEqual([
			'/account/x%20/%0A/_app/immutable/entry/start.js%20https://attacker.example/x.js%20302%0A/zz /login 303',
			'/a%E2%80%A8b%C2%A0c%0Dd%09e /login 303',
			'/a%20%23comment /login?q=a%20b%20200 303',
			'/a%3Fb%23c /login 303',
			'/a%22%3C%3E%60%7B%7D%5Eb /login 303'
		]);
		expect(warn).not.toHaveBeenCalled();
	});

	test('skips prerendered redirects containing splats or placeholders', () => {
		const warn = vi.fn();
		const content = generate_redirects(
			new Map([
				['/account/*', { status: 303, location: '/login' }],
				['/account/:id', { status: 303, location: '/login' }],
				[
					'/account/x /\n/_app/immutable/entry/* https://attacker.example/x/:splat 302\n/zz',
					{ status: 303, location: '/login' }
				]
			]),
			// @ts-ignore
			{ warn }
		);

		expect(content).toBe('');
		expect(warn).toHaveBeenCalledTimes(3);
	});
});

describe('sync_process_env', () => {
	// an empty directory so that no `.dev.vars` files are picked up
	const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'adapter-cloudflare-'));

	/**
	 * @param {Record<string, string | import('@cloudflare/config').Json>} vars
	 */
	const worker = (vars) =>
		/** @type {import('@cloudflare/vite-plugin').CloudflareConfig['worker']} */ ({
			name: 'app',
			compatibilityDate: '2026-09-01',
			env: Object.fromEntries(
				Object.entries(vars).map(([key, value]) => [
					key,
					typeof value === 'string' ? { type: 'text', value } : { type: 'json', value }
				])
			)
		});

	test('adds variables and removes the ones that are gone', () => {
		sync_process_env(worker({ SYNC_A: 'a', SYNC_B: { json: true } }), dir, 'development');
		expect(process.env.SYNC_A).toBe('a');
		expect(process.env.SYNC_B).toBe('{"json":true}');

		sync_process_env(worker({ SYNC_A: 'changed' }), dir, 'development');
		expect(process.env.SYNC_A).toBe('changed');
		expect('SYNC_B' in process.env).toBe(false);

		sync_process_env(worker({}), dir, 'development');
		expect('SYNC_A' in process.env).toBe(false);
	});

	test('does not overwrite variables set elsewhere', () => {
		process.env.SYNC_A = 'shell';
		sync_process_env(worker({ SYNC_A: 'config' }), dir, 'development');
		expect(process.env.SYNC_A).toBe('shell');

		sync_process_env(worker({}), dir, 'development');
		expect(process.env.SYNC_A).toBe('shell');
		delete process.env.SYNC_A;
	});

	test('reads secrets from the `.dev.vars` file for the mode before the default one', () => {
		const env_dir = fs.mkdtempSync(path.join(os.tmpdir(), 'adapter-cloudflare-'));
		const with_secret = /** @type {ReturnType<typeof worker>} */ ({
			...worker({}),
			env: { SYNC_SECRET: { type: 'secret' } }
		});
		try {
			fs.writeFileSync(path.join(env_dir, '.dev.vars'), 'SYNC_SECRET=default');
			fs.writeFileSync(path.join(env_dir, '.dev.vars.staging'), 'SYNC_SECRET=staging');

			sync_process_env(with_secret, env_dir, 'staging');
			expect(process.env.SYNC_SECRET).toBe('staging');

			sync_process_env(with_secret, env_dir, 'production');
			expect(process.env.SYNC_SECRET).toBe('default');

			sync_process_env(with_secret, false, 'production');
			expect('SYNC_SECRET' in process.env).toBe(false);
		} finally {
			fs.rmSync(env_dir, { recursive: true, force: true });
		}
	});
	test('leaves out `.dev.vars` keys that are not secret bindings, like the Worker', () => {
		const env_dir = fs.mkdtempSync(path.join(os.tmpdir(), 'adapter-cloudflare-'));
		try {
			fs.writeFileSync(path.join(env_dir, '.dev.vars'), 'SYNC_TEXT=dev-vars\nSYNC_OTHER=dev-vars');

			sync_process_env(worker({ SYNC_TEXT: 'config' }), env_dir, 'development');
			expect(process.env.SYNC_TEXT).toBe('config');
			expect('SYNC_OTHER' in process.env).toBe(false);

			sync_process_env(worker({}), env_dir, 'development');
		} finally {
			fs.rmSync(env_dir, { recursive: true, force: true });
		}
	});
});
