/** @import { WorkerConfig } from '@cloudflare/vite-plugin' */
import process from 'node:process';

/**
 * @param {WorkerConfig} wrangler_config
 */
export function validate_worker_settings(wrangler_config) {
	if (process.env.CF_PAGES) {
		throw new Error(
			`Cloudflare Pages is no longer supported. Deploy with Cloudflare Workers instead. Consult https://svelte.dev/docs/kit/adapter-cloudflare#Migrating-from-Cloudflare-Pages`
		);
	}

	const config_path = wrangler_config.configPath || 'your wrangler.jsonc file';

	if (wrangler_config.pages_build_output_dir) {
		throw new Error(
			`Cloudflare Pages is no longer supported. Remove \`pages_build_output_dir\` from ${config_path} and configure Cloudflare Workers instead. Consult https://svelte.dev/docs/kit/adapter-cloudflare#Migrating-from-Cloudflare-Pages`
		);
	}
}

/**
 * Adds header rules to the contents of a `_headers` file
 * @param {string} url
 * @param {string[]} rules
 * @param {string} content
 * @returns {string}
 */
export function append_headers(url, rules, content) {
	const regex = new RegExp(`^(${url.replaceAll('*', '\\*')})$`, 'm');
	const formatted_headers = rules.map((rule) => `  ${rule}`).join('\n');

	// if the URL already exists, just add header rules to it
	if (regex.test(content)) {
		return content.replace(regex, `$1\n${formatted_headers}`);
	}

	// otherwise, we add the url and header rules
	return `
${content}
# === START AUTOGENERATED SVELTE IMMUTABLE HEADERS ===
${url}
${formatted_headers}
# === END AUTOGENERATED SVELTE IMMUTABLE HEADERS ===
`.trim();
}

/**
 * The variables we copied into `process.env` and the values we set them to
 * @type {Map<string, string>}
 */
const injected_env = new Map();

/**
 * Copies Wrangler variables into `process.env` so that SvelteKit can read them
 * while it runs in Node. Variables already set elsewhere (e.g. by the shell) win.
 * Variables from a previous call that are no longer present are removed.
 * @param {Record<string, string>} vars
 * @returns {boolean} whether `process.env` changed
 */
export function sync_process_env(vars) {
	let changed = false;

	for (const [key, value] of injected_env) {
		if (vars[key] === value) continue;
		// leave it alone if something else has since changed it
		if (process.env[key] === value) {
			delete process.env[key];
			changed = true;
		}
		injected_env.delete(key);
	}

	for (const [key, value] of Object.entries(vars)) {
		if (injected_env.has(key) || key in process.env) continue;
		process.env[key] = value;
		injected_env.set(key, value);
		changed = true;
	}

	return changed;
}
